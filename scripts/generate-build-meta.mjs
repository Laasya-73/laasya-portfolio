import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const outputFile = resolve('src/lib/generated/build-meta.ts');

const runGit = (args) => {
  try {
    return execFileSync('git', args, { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  } catch {
    return '';
  }
};

const envSha =
  process.env.VERCEL_GIT_COMMIT_SHA?.slice(0, 7) ||
  process.env.GITHUB_SHA?.slice(0, 7) ||
  '';

const gitSha = runGit(['rev-parse', '--short', 'HEAD']);

const commitSha = gitSha || envSha || 'local';
// Capture once per build, independently of the source commit's date.
// Emit the display label too so SSR and hydration use the exact same text.
const buildDate = new Date();
const buildDateISO = buildDate.toISOString();
const buildDateLabel = new Intl.DateTimeFormat('en-US', {
  month: 'long',
  day: 'numeric',
  year: 'numeric',
  timeZone: 'America/Chicago'
}).format(buildDate);

mkdirSync(dirname(outputFile), { recursive: true });

const fileContents = `// Auto-generated by scripts/generate-build-meta.mjs
export const LAST_UPDATED_ISO = ${JSON.stringify(buildDateISO)};
export const LAST_UPDATED_LABEL = ${JSON.stringify(buildDateLabel)};
export const COMMIT_SHA = ${JSON.stringify(commitSha)};
`;

writeFileSync(outputFile, fileContents);
